package main

// mon module: realtime monitoring (interface traffic, CPU per core, memory, load, conntrack,
// temperature), 24 h history, per-device traffic, connections, processes and kernel log.
// No router.yaml section. Nothing stays resident except the tiny busybox-sh history sampler
// (rootfs/usr/libexec/mr/mon-collect, service mr-mon); everything else is computed on demand by
// the `mr api` CGI (web UI) or `mr mon ...` (CLI / agent). Docs: docs/modules/mon.md.
//
// Files: mod_mon.go (module, mon.now, CLI), mod_mon_hist.go (mon.history),
// mod_mon_ct.go (conntrack: mon.devices, mon.conns), mod_mon_sys.go (mon.procs, mon.dmesg),
// mod_mon_linux.go / mod_mon_other.go (rtnetlink neighbour dump, kernel log syscall).

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"
)

const (
	monDir      = "/run/mr-mon" // RAM only (tmpfs): history ring + per-flow byte snapshot
	monHistFile = monDir + "/history"
	monFlowFile = monDir + "/flows"
	monSysctl   = "/etc/sysctl.d/91-mon.conf"
	monConfD    = "/etc/conf.d/mr-mon"
)

// monRoot prefixes every /proc, /sys, /run and lease path the module reads (tests use a fake tree).
var monRoot = ""

func monPath(p string) string { return monRoot + p }

func init() {
	register(&Module{
		Name:   "mon",
		Prio:   50,
		Render: monRender,
		// the history sampler is always on: ~1 MB RSS, one sample per minute
		Services: func(c *Config) []string { return []string{"mr-mon"} },
		Managed:  []string{"mr-mon"},
		Restart: func(path string) string {
			switch path {
			case monSysctl:
				return "sysctl"
			case monConfD:
				return "mr-mon"
			}
			return ""
		},
		RestartOrder: []string{"mr-mon"},
		API: map[string]func(r apiReq) apiResp{
			"mon.now":     monAPI(true, func(c *Config, _ []byte) (any, error) { return monNow(c), nil }),
			"mon.history": monAPI(true, func(c *Config, _ []byte) (any, error) { return monHistoryFor(c, monPath(monHistFile)) }),
			"mon.devices": monAPI(true, func(c *Config, _ []byte) (any, error) { return monDevices(c) }),
			"mon.conns":   monAPI(true, monConns),
			"mon.procs":   monAPI(false, func(*Config, []byte) (any, error) { return monProcs(), nil }),
			"mon.dmesg":   monAPI(false, func(*Config, []byte) (any, error) { return monDmesg() }),
		},
		Commands: map[string]func(c *Config, args []string) error{"mon": monCmd},
	})
}

// monRender: conntrack byte accounting (per-device traffic) and the sampler's WAN device list.
func monRender(c *Config, out *Out) error {
	out.Add(monSysctl, 0644, "# generated by mr (mon) — per-connection byte/packet counters for per-device traffic\n"+
		"net.netfilter.nf_conntrack_acct=1\n")
	out.Add(monConfD, 0644, fmt.Sprintf("# generated by mr (mon) — physical WAN devices whose counters the history sampler sums\nMON_WAN=%q\n",
		strings.Join(monWANDevs(c), " ")))
	return nil
}

// monWANDevs: the distinct physical WAN devices. Both PPPoE sessions of the home config share
// `wan`; the physical device also sees flow-offloaded packets that bypass pppoe-* counters.
// Names go into a shell-sourced file, so anything that is not a plain netdev name is dropped.
func monWANDevs(c *Config) []string {
	var out []string
	seen := map[string]bool{}
	if c == nil {
		return out
	}
	for _, w := range c.WAN {
		d := w.Device
		if d == "" || d == "." || d == ".." || !reDev.MatchString(d) || seen[d] {
			continue
		}
		seen[d] = true
		out = append(out, d)
	}
	return out
}

// monAPI adapts a read-only handler (GET or POST, no side effects on the router). With needCfg it
// loads router.yaml for names/roles; handlers cope with a nil config if the file is broken.
func monAPI(needCfg bool, f func(c *Config, body []byte) (any, error)) func(r apiReq) apiResp {
	return func(r apiReq) apiResp {
		var c *Config
		if needCfg {
			if lc, err := loadConfig(ConfigPath, SecretsPath); err == nil {
				c = lc
			}
		}
		v, err := f(c, r.body)
		if err != nil {
			return errResp(400, "%v", err)
		}
		return apiResp{body: v}
	}
}

// monCmd: `mr mon now|history [FILE]|devices|conns [FILTER-JSON]|procs|dmesg` prints the same JSON
// as the web UI API, for agents and SSH.
func monCmd(c *Config, args []string) error {
	if len(args) == 0 {
		return fmt.Errorf("usage: mr mon now | history [FILE] | devices | conns ['{\"proto\":\"tcp\",\"limit\":50}'] | procs | dmesg")
	}
	var v any
	var err error
	switch args[0] {
	case "now":
		v = monNow(c)
	case "history":
		p := monPath(monHistFile)
		if len(args) > 1 {
			p = args[1]
		}
		v, err = monHistoryFor(c, p)
	case "devices":
		v, err = monDevices(c)
	case "conns":
		var body []byte
		if len(args) > 1 {
			body = []byte(args[1])
		}
		v, err = monConns(c, body)
	case "procs":
		v = monProcs()
	case "dmesg":
		v, err = monDmesg()
	default:
		return fmt.Errorf("mr mon: unknown view %q", args[0])
	}
	if err != nil {
		return err
	}
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", " ")
	return enc.Encode(v)
}

