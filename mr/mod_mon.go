type monIface struct {
	Name  string `json:"name"`
	Role  string `json:"role,omitempty"`     // wan | wan-dev | lan | port | wifi | vpn
	State string `json:"state"`              // up | down | … (operstate; ppp/tun "unknown" resolved by IFF_UP|IFF_RUNNING)
	Raw   string `json:"oper_raw,omitempty"` // the kernel's operstate when State was derived from the flags
	RX    uint64 `json:"rx"`                 // bytes
	TX    uint64 `json:"tx"`
	RXP   uint64 `json:"rxp"` // packets
	TXP   uint64 `json:"txp"`
	Err   uint64 `json:"err"`  // rx + tx errors
	Drop  uint64 `json:"drop"` // rx + tx drops
}

// monDisk: a filesystem the monitor shows (config storage on flash, /tmp in RAM).
type monDisk struct {
	Name    string `json:"name"` // config | tmp
	Path    string `json:"path"`
	TotalKB int64  `json:"total_kb"`
	AvailKB int64  `json:"avail_kb"`
}

func monDisks() []monDisk {
	out := []monDisk{}
	for _, d := range []monDisk{{Name: "config", Path: "/etc/mini-router"}, {Name: "tmp", Path: "/tmp"}} {
		if d.TotalKB, d.AvailKB = dfKB(d.Path); d.TotalKB > 0 {
			out = append(out, d)
		}
	}
	return out
}

type monTemp struct {
	Zone string `json:"zone"`
	Type string `json:"type"`
	MC   int64  `json:"mc"` // millidegrees Celsius
}

func monNow(c *Config) map[string]any {
	cpu, cpus := monParseStat(readFile(monPath("/proc/stat")))
	mem := monParseMeminfo(readFile(monPath("/proc/meminfo")))
	st := map[string]any{
		"t":    time.Now().UnixMilli(),
		"up":   monUptime(),
		"hz":   100,  // USER_HZ of /proc/stat
		"cpu":  cpu,  // user nice system idle iowait irq softirq steal (jiffies, cumulative)
		"cpus": cpus, // same, per core
		"mem": map[string]int64{
			"total": mem["MemTotal"], "avail": mem["MemAvailable"], "free": mem["MemFree"],
			"buffers": mem["Buffers"], "cached": mem["Cached"], "swap_total": mem["SwapTotal"], "swap_free": mem["SwapFree"],
		},
		"ct":     atoi(strings.TrimSpace(readFile(monPath("/proc/sys/net/netfilter/nf_conntrack_count")))),
		"ct_max": atoi(strings.TrimSpace(readFile(monPath("/proc/sys/net/netfilter/nf_conntrack_max")))),
		"temps":  monTemps(),
		"disks":  monDisks(),
		"ifaces": monIfaces(c),
	}
	if f := strings.Fields(readFile(monPath("/proc/loadavg"))); len(f) >= 4 {
		st["load"] = []float64{atof(f[0]), atof(f[1]), atof(f[2])}
		if r, t, ok := strings.Cut(f[3], "/"); ok {
			st["procs_running"], st["procs"] = atoi(r), atoi(t)
		}
	}
	return st
}

func monUptime() float64 { return atof(firstField(readFile(monPath("/proc/uptime")))) }

// monParseStat returns the aggregate and per-core counters (8 fields each) of /proc/stat.
func monParseStat(s string) ([]uint64, [][]uint64) {
	var total []uint64
	cores := [][]uint64{}
	for _, l := range strings.Split(s, "\n") {
		if !strings.HasPrefix(l, "cpu") {
			continue
		}
		f := strings.Fields(l)
		v := make([]uint64, 8)
		for i := 0; i < 8 && i+1 < len(f); i++ {
			v[i], _ = strconv.ParseUint(f[i+1], 10, 64)
		}
		if f[0] == "cpu" {
			total = v
		} else {
			cores = append(cores, v)
		}
	}
	return total, cores
}

func monParseMeminfo(s string) map[string]int64 {
	m := map[string]int64{}
	for _, l := range strings.Split(s, "\n") {
		f := strings.Fields(l)
		if len(f) >= 2 {
			m[strings.TrimSuffix(f[0], ":")], _ = strconv.ParseInt(f[1], 10, 64)
		}
	}
	return m
}

func monTemps() []monTemp {
	out := []monTemp{}
	zones, _ := filepath.Glob(monPath("/sys/class/thermal/thermal_zone*"))
	sort.Strings(zones)
	for _, z := range zones {
		t := strings.TrimSpace(readFile(z + "/temp"))
		if t == "" {
			continue
		}
		v, _ := strconv.ParseInt(t, 10, 64)
		out = append(out, monTemp{Zone: filepath.Base(z), Type: strings.TrimSpace(readFile(z + "/type")), MC: v})
	}
	return out
}

// monRoles labels netdevs by what router.yaml says they are, then by what sysfs says.
func monRoles(c *Config) map[string]string {
	r := map[string]string{}
	if c == nil {
		return r
	}
	for _, w := range c.WAN {
		r[w.Device] = "wan-dev"
	}
	for _, w := range c.WAN {
		r[w.Ifname()] = "wan"
	}
	for _, b := range c.LANBridges() {
		r[b] = "lan"
	}
	return r
}

func monIfaces(c *Config) []monIface {
	roles := monRoles(c)
	out := []monIface{}
	for _, l := range strings.Split(readFile(monPath("/proc/net/dev")), "\n") {
		name, rest, ok := strings.Cut(l, ":")
		name = strings.TrimSpace(name)
		if !ok || name == "" || name == "lo" || strings.Contains(name, "|") {
			continue
		}
		f := strings.Fields(rest)
		if len(f) < 16 {
			continue
		}
		n := func(i int) uint64 { v, _ := strconv.ParseUint(f[i], 10, 64); return v }
		sys := monPath("/sys/class/net/" + name)
		raw := strings.TrimSpace(readFile(sys + "/operstate"))
		it := monIface{Name: name, Role: roles[name], State: effOper(raw, readFile(sys+"/flags")),
			RX: n(0), RXP: n(1), TX: n(8), TXP: n(9), Err: n(2) + n(10), Drop: n(3) + n(11)}
		if raw != it.State {
			it.Raw = raw
		}
		if it.Role == "" {
			switch {
			case monExists(sys + "/phy80211"):
				it.Role = "wifi"
			case monExists(sys + "/brport"):
				it.Role = "port"
			case name == "tailscale0" || strings.HasPrefix(name, "tun") || strings.HasPrefix(name, "wg"):
				it.Role = "vpn"
			}
		}
		out = append(out, it)
	}
	return out
}

func monExists(p string) bool { _, err := os.Stat(p); return err == nil }
