func TestSysFirmwareUpload(t *testing.T) {
	d := t.TempDir()
	oldS, oldF, oldD, oldR := fwSysupgrade, fwFactoryReset, fwDir, fwRunDir
	t.Cleanup(func() { fwSysupgrade, fwFactoryReset, fwDir, fwRunDir = oldS, oldF, oldD, oldR })
	fwSysupgrade, fwFactoryReset = filepath.Join(d, "sysupgrade"), filepath.Join(d, "factory-reset")
	fwDir, fwRunDir = filepath.Join(d, "up"), filepath.Join(d, "run")
	// a symlink or foreign file where the private upload dir goes is replaced, never followed
	os.Symlink(d, fwDir)
	post := func(f func(apiReq) apiResp, body any) apiResp {
		b, _ := json.Marshal(body)
		return f(apiReq{method: "POST", body: b})
	}
	img := bytes.Repeat([]byte("firmware-"), 1000)
	chunk := func(off, n int) map[string]any {
		return map[string]any{"offset": off, "total": len(img), "data": base64.StdEncoding.EncodeToString(img[off : off+n])}
	}
	if r := post(apiSysFwUpload, chunk(0, 4000)); r.status != 501 {
		t.Errorf("upload without the platform script: %d", r.status)
	}
	if st := apiSysFw(apiReq{method: "GET"}).body.(map[string]any); st["sysupgrade"] != false {
		t.Error("sysupgrade reported without the script")
	}
	os.WriteFile(fwSysupgrade, []byte("#!/bin/sh\necho \"refused: $1 is not an AX6000 image\" >&2\nexit 3\n"), 0755)
	if r := post(apiSysFwUpload, chunk(0, 4000)); r.status != 0 {
		t.Fatalf("first chunk: %v", r.body)
	}
	r := post(apiSysFwUpload, chunk(5000, 1000)) // gap
	if r.status != 409 || r.body.(map[string]any)["received"] != int64(4000) {
		t.Errorf("gap accepted: %d %v", r.status, r.body)
	}
	if r := post(apiSysFwUpgrade, map[string]any{"sha256": strings.Repeat("0", 64)}); r.status != 409 {
		t.Errorf("upgrade with a partial image: %d", r.status)
	}
	if r := post(apiSysFwUpload, chunk(4000, len(img)-4000)); r.status != 0 {
		t.Fatalf("last chunk: %v", r.body)
	}
	if r := post(apiSysFwUpload, map[string]any{"offset": len(img) - 10, "total": len(img), "data": base64.StdEncoding.EncodeToString(make([]byte, 20))}); r.status != 400 {
		t.Errorf("chunk past the end: %d", r.status)
	}
	if fi, err := os.Lstat(fwDir); err != nil || !fi.IsDir() || fi.Mode().Perm() != 0700 {
		t.Errorf("upload dir: %v %v", fi, err)
	}
	if b, _ := os.ReadFile(fwImage()); !bytes.Equal(b, img) {
		t.Fatal("assembled image differs")
	}
	if r := post(apiSysFwUpgrade, map[string]any{"sha256": strings.Repeat("0", 64)}); r.status != 400 {
		t.Errorf("sha mismatch accepted: %d", r.status)
	}
	sum := sha256.Sum256(img)
	if r := post(apiSysFwUpgrade, map[string]any{"sha256": strings.ToUpper(hex.EncodeToString(sum[:]))}); r.status != 0 {
		t.Fatalf("upgrade: %v", r.body)
	}
	// the (fake) platform script refuses: its exit code and stderr reach the status
	var st map[string]any
	for i := 0; i < 50; i++ {
		st = fwRunStatus()
		if st["state"] != "running" {
			break
		}
		time.Sleep(100 * time.Millisecond)
	}
	if st["state"] != "failed" || st["rc"] != 3 || !strings.Contains(st["message"].(string), "refused: "+fwImage()) {
		t.Errorf("run status: %v", st)
	}
	if r := post(apiSysFactoryReset, map[string]any{"confirm": "yes"}); r.status != 400 {
		t.Errorf("factory reset without RESET: %d", r.status)
	}
	if r := post(apiSysFactoryReset, map[string]any{"confirm": "RESET"}); r.status != 501 {
		t.Errorf("factory reset without the script: %d", r.status)
	}
	if r := post(apiSysFwUpload, map[string]any{"cancel": true}); r.status != 0 {
		t.Error("cancel")
	}
	if _, err := os.Stat(fwImage()); err == nil {
		t.Error("cancel kept the image")
	}
}

