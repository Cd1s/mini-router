func tarGz(t *testing.T, entries ...[3]string) []byte { // name, typeflag ("0", "5", "2"), content
	t.Helper()
	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)
	for _, e := range entries {
		h := &tar.Header{Name: e[0], Typeflag: e[1][0], Mode: 0644, Size: int64(len(e[2]))}
		if e[1] != "0" {
			h.Size = 0
		}
		if e[1] == "2" {
			h.Linkname = "/etc/passwd"
		}
		tw.WriteHeader(h)
		if e[1] == "0" {
			tw.Write([]byte(e[2]))
		}
	}
	tw.Close()
	gz.Close()
	return buf.Bytes()
}

