// sysTemp points the files the sys module reads while rendering at a temp dir.
func sysTemp(t *testing.T) string {
	t.Helper()
	d := t.TempDir()
	oldAK, oldCron := authKeysFile, cronFile
	authKeysFile, cronFile = filepath.Join(d, "authorized_keys"), filepath.Join(d, "crontab")
	t.Cleanup(func() { authKeysFile, cronFile = oldAK, oldCron })
	return d
}

// fakeKey builds a syntactically valid public key line (type string + 32 bytes in the blob).
func fakeKey(typ string, seed byte, comment string) string {
	var b []byte
	put := func(s []byte) {
		var l [4]byte
		binary.BigEndian.PutUint32(l[:], uint32(len(s)))
		b = append(append(b, l[:]...), s...)
	}
	put([]byte(typ))
	put(bytes.Repeat([]byte{seed}, 32))
	line := typ + " " + base64.StdEncoding.EncodeToString(b)
	if comment != "" {
		line += " " + comment
	}
	return line
}

func TestSysParseTZ(t *testing.T) {
	good := map[string][2]int{ // std offset, dst offset (east of UTC)
		"<+07>-7":                        {25200, 0},
		"UTC0":                           {0, 0},
		"CST-8":                          {28800, 0},
		"IST-5:30":                       {19800, 0},
		"<-03>3":                         {-10800, 0},
		"CET-1CEST,M3.5.0,M10.5.0/3":     {3600, 7200},
		"EST5EDT,M3.2.0,M11.1.0":         {-18000, -14400},
		"AEST-10AEDT,M10.1.0,M4.1.0/3":   {36000, 39600},
		"NZST-12NZDT,M9.5.0,M4.1.0/3":    {43200, 46800},
		"<+0330>-3:30":                   {12600, 0},
		"ABC+5DEF+4:30,J60/2,300/1:30:5": {-18000, -16200},
	}
	for s, want := range good {
		z, err := parseTZ(s)
		if err != nil {
			t.Errorf("%q rejected: %v", s, err)
			continue
		}
		if z.StdOff != want[0] || (z.HasDST && z.DSTOff != want[1]) {
			t.Errorf("%q: offsets %d/%d, want %v", s, z.StdOff, z.DSTOff, want)
		}
	}
	for _, s := range []string{"", "Asia/Bangkok", ":Asia/Bangkok", "UT0", "CET", "CET-1CEST", "<+7>-7", "<+07-7",
		"UTC0\n", "UTC0;reboot", "UTC 0", "UTC25", "CET-1CEST,M3.5.0", "CET-1CEST,M13.5.0,M10.5.0", "CET-1CEST,M3.6.0,M10.5.0",
		"CET-1CEST,M3.5.7,M10.5.0", "CET-1CEST,M3.5.0,M10.5.0/25", "CET-1CEST,J0,J365", "CET-1CEST,M3.5.0,M10.5.0,x",
		"UTC0'", `UTC0"`, "UTC-1:60", strings.Repeat("A", 70) + "0"} {
		if _, err := parseTZ(s); err == nil {
			t.Errorf("%q accepted", s)
		}
	}
}

func TestSysTZif(t *testing.T) {
	jan := time.Date(2026, 1, 15, 12, 0, 0, 0, time.UTC)
	jul := time.Date(2026, 7, 15, 12, 0, 0, 0, time.UTC)
	past := time.Date(1990, 7, 1, 0, 0, 0, 0, time.UTC)
	for tz, want := range map[string][3]int{ // offset in January, July, July 1990
		"<+07>-7":                      {25200, 25200, 25200},
		"UTC0":                         {0, 0, 0},
		"IST-5:30":                     {19800, 19800, 19800},
		"CET-1CEST,M3.5.0,M10.5.0/3":   {3600, 7200, 7200},
		"EST5EDT,M3.2.0,M11.1.0":       {-18000, -14400, -14400},
		"AEST-10AEDT,M10.1.0,M4.1.0/3": {39600, 36000, 36000},
	} {
		data, err := tzifFromPOSIX(tz)
		if err != nil {
			t.Fatalf("%s: %v", tz, err)
		}
		if !bytes.HasPrefix(data, []byte("TZif2")) || !bytes.HasSuffix(data, []byte("\n"+tz+"\n")) {
			t.Errorf("%s: bad framing", tz)
		}
		loc, err := time.LoadLocationFromTZData(tz, data)
		if err != nil {
			t.Fatalf("%s: Go rejects the TZif: %v", tz, err)
		}
		for i, at := range []time.Time{jan, jul, past} {
			if _, off := at.In(loc).Zone(); off != want[i] {
				t.Errorf("%s at %s: offset %d, want %d", tz, at.Format("2006-01"), off, want[i])
			}
		}
	}
	if name, _ := jul.In(sysLocation(&Config{System: System{Timezone: "CET-1CEST,M3.5.0,M10.5.0/3"}})).Zone(); name != "CEST" {
		t.Errorf("zone name %q, want CEST", name)
	}
	if sysLocation(&Config{}).String() != "UTC0" {
		t.Error("empty timezone must be UTC")
	}
}

