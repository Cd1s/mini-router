	if errs := c.Validate(); len(errs) > 0 {
		t.Fatal(errs)
	}
	existing := "# keys from the image build\n" + fakeKey("ssh-ed25519", 9, "image") + "\n" + `no-pty ` + fakeKey("ssh-rsa", 8, "") + "\n"
	os.WriteFile(authKeysFile, []byte(existing), 0600)
	f := renderMap(t, c)
	if got := f["/etc/conf.d/dropbear"]; got != "# generated by mr\nDROPBEAR_OPTS=\"-p 192.168.1.6:2222 -p 192.168.30.1:2222 -K 300\"\n" {
		t.Errorf("dropbear: %q", got)
	}
	ak := f[authKeysFile]
	want := existing + akBegin + "\n" + k1 + "\n" + k2 + "\n" + akEnd + "\n"
	if ak != want {
		t.Fatalf("authorized_keys:\n%s\nwant:\n%s", ak, want)
	}
	// idempotent, block replaced in place, unmanaged lines kept (also after the block)
	os.WriteFile(authKeysFile, []byte(ak+"ssh-ed25519 added-by-hand-after\n"), 0600)
	c.Services.SSH.Keys = []string{k2}
	ak2 := renderMap(t, c)[authKeysFile]
	if ak2 != existing+akBegin+"\n"+k2+"\n"+akEnd+"\nssh-ed25519 added-by-hand-after\n" {
		t.Errorf("replace in place:\n%s", ak2)
	}
	// no managed keys left: the block goes, everything else stays
	os.WriteFile(authKeysFile, []byte(ak2), 0600)
	c.Services.SSH.Keys = nil
	if got := renderMap(t, c)[authKeysFile]; got != existing+"ssh-ed25519 added-by-hand-after\n" {
		t.Errorf("remove block:\n%s", got)
	}
