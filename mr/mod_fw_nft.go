func quoteList(xs []string) string {
	q := make([]string, len(xs))
	for i, x := range xs {
		q[i] = fmt.Sprintf("%q", x)
	}
	return strings.Join(q, ", ")
}

func nftPorts(p string) string { return p } // "a-b" is already nft range syntax

func netdevExists(name string) bool {
	_, err := os.Stat("/sys/class/net/" + name)
	return err == nil
}

// fwLockFile serializes reloads: the runtime state a reload carries over (learned sets, pauses) is
// read under it, so two reloads at once (a PPPoE hook during `mr pause`) cannot load a stale copy last.
var fwLockFile = RunDir + "/fw.lock"

// fwLoad renders against live devices and loads atomically; keeps the last good ruleset on failure.
func fwLoad(c *Config) error {
	if lk := flock(fwLockFile, true); lk != nil {
		defer lk.Close()
	}
	rules := renderNft(c, netdevExists)
	path := GenDir + "/nftables.nft"
	tmp := path + ".new"
	if err := os.WriteFile(tmp, []byte(rules), 0644); err != nil {
		return err
	}
	if out, err := run("nft", "-c", "-f", tmp); err != nil {
		os.Remove(tmp)
		return fmt.Errorf("nft check failed: %v\n%s", err, out)
	}
	// The learned access-control sets are refilled in the same transaction that replaces the
	// ruleset. Refilled afterwards, a reply packet of a controlled device's running download that
	// arrives in between (sets still empty) puts the connection into the flowtable (hardware
	// offload), where a later time window can no longer cut it.
	var elems string
	if len(fwAccessEntries(c)) > 0 {
		elems = fwAccessScript(c, fwLearned())
	}
	// the addresses dnsmasq learned for policy_routes domains (net module): dnsmasq only adds them when
	// it asks upstream, so a reload that emptied the sets would send cached names to the wrong WAN
	elems += policyDomainCarry(c)
	// active pauses (dev module): their sets and rules, in the same transaction. Replacing the table
	// also replaces the flowtable, so a paused device's offloaded flows come back to the CPU path,
	// where these rules drop them in both directions.
	elems += pauseScript(c)
	loaded := false
	if elems != "" {
		if out, err := runStdin(rules+elems, "nft", "-f", "-"); err == nil {
			loaded = true
		} else {
			logf("fw: loading with the learned set addresses failed, loading without: %v %s", err, strings.TrimSpace(out))
		}
	}
	if !loaded {
		if out, err := run("nft", "-f", tmp); err != nil {
			os.Remove(tmp)
			return fmt.Errorf("nft load failed: %v\n%s", err, out)
		}
		if elems != "" {
			if out, err := runStdin(elems, "nft", "-f", "-"); err != nil {
				logf("fw: learned set addresses: %v %s", err, strings.TrimSpace(out)) // best effort: the sets also learn from traffic
			}
		}
	}
	if err := os.Rename(tmp, path); err != nil {
		return err
	}
	return refreshLan6()
}

// refreshLan6 keeps @lan6 = link-local + multicast + the global prefixes currently on the LAN bridge.
func refreshLan6() error {
	c, err := loadConfig(ConfigPath, SecretsPath)
	if err != nil {
		return err
	}
	out, err := run("ip", "-6", "-o", "addr", "show", "dev", c.LAN.Bridge, "scope", "global")
	if err != nil {
		return nil // bridge not up yet
	}
	elems := []string{"fe80::/10", "ff00::/8"}
	for _, l := range strings.Split(out, "\n") {
		f := strings.Fields(l)
		for i := 0; i+1 < len(f); i++ {
			if f[i] == "inet6" {
				if _, n, err := net.ParseCIDR(f[i+1]); err == nil {
					elems = append(elems, n.String())
				}
			}
		}
	}
	script := fmt.Sprintf("flush set inet mr lan6\nadd element inet mr lan6 { %s }\n", strings.Join(dedup(elems), ", "))
	script += pd6Script(c)
	_, err = runStdin(script, "nft", "-f", "-")
	return err
}

func dedup(xs []string) []string {
	seen := map[string]bool{}
	var o []string
	for _, x := range xs {
		if !seen[x] {
			seen[x] = true
			o = append(o, x)
		}
	}
	return o
}
