func dnsFiles(t *testing.T, c *Config) map[string]string {
	t.Helper()
	if errs := c.Validate(); len(errs) > 0 {
		t.Fatalf("config invalid:\n%s", strings.Join(errs, "\n"))
	}
	files, err := Render(c)
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]string{}
	for _, f := range files {
		got[f.Path] = f.Data
	}
	return got
}

func wantErrs(t *testing.T, c *Config, subs ...string) {
	t.Helper()
	errs := strings.Join(c.Validate(), "\n")
	for _, s := range subs {
		if !strings.Contains(errs, s) {
			t.Errorf("want error containing %q, got:\n%s", s, errs)
		}
	}
}

