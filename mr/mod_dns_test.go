// dnsTestReply builds a reply to query q with the given answers (each a pre-encoded RR after the name pointer).
func dnsTestReply(q []byte, answers ...[]byte) []byte {
	r := append([]byte{}, q...)
	binary.BigEndian.PutUint16(r[2:], 0x8180)
	binary.BigEndian.PutUint16(r[6:], uint16(len(answers)))
	for _, a := range answers {
		r = append(r, 0xC0, 12) // name = the question name
		r = append(r, a...)
	}
	return r
}

func rrBytes(typ, class uint16, ttl uint32, rdata []byte) []byte {
	b := make([]byte, 10)
	binary.BigEndian.PutUint16(b, typ)
	binary.BigEndian.PutUint16(b[2:], class)
	binary.BigEndian.PutUint32(b[4:], ttl)
	binary.BigEndian.PutUint16(b[8:], uint16(len(rdata)))
	return append(b, rdata...)
}

func txtData(ss ...string) []byte {
	var b []byte
	for _, s := range ss {
		b = append(b, byte(len(s)))
		b = append(b, s...)
	}
	return b
}

func TestDNSParseResponse(t *testing.T) {
	q, err := dnsEncodeQuery(0x1234, "nas.lan.", dnsTypeA, dnsClassIN)
	if err != nil {
		t.Fatal(err)
	}
	srv := append([]byte{0, 0, 0, 5, 0x01, 0xbd}, 0xC0, 12) // prio 0 weight 5 port 445 target = nas.lan
	msg := dnsTestReply(q,
		rrBytes(dnsTypeA, 1, 60, []byte{192, 168, 1, 10}),
		rrBytes(dnsTypeCNAME, 1, 60, []byte{0xC0, 12}),
		rrBytes(dnsTypeSRV, 1, 60, srv),
		rrBytes(dnsTypeTXT, 1, 0, txtData("a b", "c")),
		rrBytes(dnsTypeAAAA, 1, 60, net.ParseIP("fd00::10")))
	rc, rrs, err := dnsParseResponse(msg, 0x1234)
	if err != nil || rc != 0 || len(rrs) != 5 {
		t.Fatalf("rc %d err %v rrs %+v", rc, err, rrs)
	}
	want := []string{"192.168.1.10", "nas.lan", "0 5 445 nas.lan", "a b c", "fd00::10"}
	for i, w := range want {
		if rrs[i].Data != w || rrs[i].Name != "nas.lan" {
			t.Errorf("rr %d = %+v, want %q", i, rrs[i], w)
		}
	}
	if _, _, err := dnsParseResponse(msg, 0x4321); err != errDNSWrongID {
		t.Error("id not checked")
	}
	// no truncation or corruption may panic
	for n := 0; n < len(msg); n++ {
		dnsParseResponse(msg[:n], 0x1234)
		bad := append([]byte{}, msg...)
		bad[n] ^= 0xff
		dnsParseResponse(bad, 0x1234)
	}
	loop := append(append([]byte{}, msg[:12]...), 0xC0, 12, 0, 1, 0, 1)
	binary.BigEndian.PutUint16(loop[4:], 1)
	if _, _, err := dnsParseResponse(loop, 0x1234); err == nil {
		t.Error("compression loop accepted")
	}
	if _, err := dnsEncodeQuery(1, "a..b", dnsTypeA, dnsClassIN); err == nil {
		t.Error("empty label accepted")
	}
}

// A fake dnsmasq answering the CHAOS statistics queries end to end over UDP.
func TestDnsmasqStatsQuery(t *testing.T) {
	pc, err := net.ListenPacket("udp", "127.0.0.1:0")
	if err != nil {
		t.Skip(err)
	}
	defer pc.Close()
	vals := map[string][]string{"cachesize.bind": {"8000"}, "insertions.bind": {"120"}, "evictions.bind": {"0"},
		"hits.bind": {"900"}, "misses.bind": {"100"}, "servers.bind": {"127.0.0.1#5453 40 1", "192.0.2.1#53 60 0"}}
	go func() {
		buf := make([]byte, 512)
		for {
			n, addr, err := pc.ReadFrom(buf)
			if err != nil {
				return
			}
			q := append([]byte{}, buf[:n]...)
			name, next, _ := dnsReadName(q, 12)
			if binary.BigEndian.Uint16(q[next+2:]) != dnsClassCHAOS {
				continue
			}
			pc.WriteTo(dnsTestReply(q, rrBytes(dnsTypeTXT, dnsClassCHAOS, 0, txtData(vals[name]...))), addr)
		}
	}()
	st, err := queryDnsmasqStats(pc.LocalAddr().String())
	if err != nil {
		t.Fatal(err)
	}
	if st.CacheSize != 8000 || st.Insertions != 120 || st.Hits != 900 || st.Misses != 100 || len(st.Servers) != 2 ||
		st.Servers[0] != (upstreamStat{"127.0.0.1#5453", 40, 1}) || st.Servers[1].Queries != 60 {
		t.Fatalf("%+v", st)
	}
}

func TestDNSConfigJSONRoundTrip(t *testing.T) {
	c := testConfig(t)
	c.DNS.Records = []Record{{"nas", "A", "192.168.1.10"}}
	c.DHCP.HostLeases = map[string]string{"02:c3:06:d6:7f:8a": "infinite"}
	c.DHCP.Options = []DHCPOpt{{26, "1492"}}
	c.DHCP.IPv6.Mode = "stateless"
	c.DNS.Upstream = "manual"
	c.DNS.Servers = []string{"1.1.1.1"}
	m, err := configToJSON(c)
	if err != nil {
		t.Fatal(err)
	}
	raw, _ := json.Marshal(m)
	back, _, err := configFromJSON(raw)
	if err != nil {
		t.Fatal(err)
	}
	back.secrets = c.secrets
	back.defaults()
	back.DNS.Split = c.DNS.Split
	if len(back.DNS.Records) != 1 || back.DHCP.HostLeases["02:c3:06:d6:7f:8a"] != "infinite" || back.DHCP.Options[0].Code != 26 ||
		back.DHCP.IPv6.Mode != "stateless" || back.DNS.Upstream != "manual" || back.DNS.DoT.Port != 5453 {
		t.Fatalf("round trip lost dns data: %+v %+v", back.DNS, back.DHCP)
	}
	if errs := back.Validate(); len(errs) > 0 {
		t.Fatal(errs)
	}
	// the UI always sees these keys, so it never has to create them (that would mark the page dirty)
	js := string(raw)
	for _, k := range []string{`"records":[`, `"host_leases":{`, `"options":[`, `"ipv6":{`, `"search":[`, `"dot":{`} {
		if !strings.Contains(js, k) {
			t.Errorf("config JSON lacks %s", k)
		}
	}
}

